#!/usr/bin/env node
// tools/import-twrp-devices.mjs — generate the /device content collection
// (src/content/devices/*.md, one file per device, frontmatter ONLY — all
// page prose lives in src/layouts/Device.astro so future edits are
// single-point).
//
// WHAT WE IMPORT: the public TWRP device list + its factual metadata fields
// (title, oem, codename, support status, maintainer names, device-tree URL,
// download folder). Facts only — we copy NO prose, notes, or any other
// content from the source, and the generated pages carry no source
// attribution (owner ruling 2026-11-08). Field names are kept verbatim
// (lowercase) for provenance clarity.
//
// SOURCE: tarball of github.com/TeamWin/twrpme @ master (the generator repo
// behind the official TWRP site's device pages). Fetched fresh on every run
// — re-run this script to re-sync the catalog.
//
// SCOPE (owner ruling 2026-11-08): devices whose support status is exactly
// 'Current' (case-insensitive) — see isCurrentStatus() in
// src/lib/devices.js.
//   PLAN FOR 'ALL' LATER: run with `--all` to import every status (observed
//   upstream values on 2026-11-08: 'No longer updated', 'No Longer
//   Supported', 'Unified', 'Beta', empty, …). Before shipping that, the
//   layout must render non-Current statuses honestly (never overstate
//   support), the /device index should gain status grouping, and stale
//   devices should get visibly older 'Listed' dates. Do NOT flip to --all
//   output without that layout work.
//
// SLUGS: codename-based (owner ruling 2026-11-08). Collision rule is
// deterministic and pinned by src/lib/devices.test.js — first device
// (sorted by oem, title) keeps the bare codename, later ones get
// <codename>-<oem>[-N]. Collisions resolved on the 2026-11-08 import:
// 'bardock' (BQ Aquaris X vs X Pro) and 'odin' (Sony Xperia ZL vs Xiaomi
// Mi Mix 4).
//
// MULTI-FOLDER DEVICES: upstream `downloadfolder` values that are not a
// single folder (multi-SKU lists like 'ROG Phone 5|I005D|ROG Phone 5S|
// I005DS') are parsed by parseDownloadVariants() into labeled per-SKU
// mirrors (`variants:` in frontmatter, rendered as a table by the layout).
// Values that fail parsing are still dropped (logged below) — never guess.
//
// Usage:
//   node tools/import-twrp-devices.mjs          # Current devices only
//   node tools/import-twrp-devices.mjs --all    # every status (NOT for
//                                               # shipping yet — see PLAN)
//
// The script is self-cleaning: it deletes only files carrying the generated
// marker comment before regenerating, so devices that disappear upstream
// vanish from the catalog and hand-made files are never touched.

import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  allocateSlugs,
  cleanMaintainers,
  decodeEntities,
  isCurrentStatus,
  isDownloadFolder,
  parseDownloadVariants,
  slugify,
} from '../src/lib/devices.js'

const TARBALL_URL = 'https://codeload.github.com/TeamWin/twrpme/tar.gz/refs/heads/master'
const MARKER = 'Generated by tools/import-twrp-devices.mjs — do not edit by hand.'
const HERE = dirname(fileURLToPath(import.meta.url))
const OUT_DIR = join(HERE, '..', 'src', 'content', 'devices')
const OVERRIDES_DIR = join(HERE, 'device-overrides')

// Hand-maintained per-device enrichments (<slug>.json: notes, factoryimages)
// merged at generation time — they survive re-syncs while the generated
// files stay strictly do-not-edit.
const overrides = new Map()
try {
  for (const f of readdirSync(OVERRIDES_DIR)) {
    if (f.endsWith('.json')) {
      overrides.set(f.slice(0, -5), JSON.parse(readFileSync(join(OVERRIDES_DIR, f), 'utf8')))
    }
  }
} catch {
  // No overrides directory yet — nothing to merge.
}

const importAll = process.argv.includes('--all')

// --- fetch + unpack -------------------------------------------------------

const work = mkdtempSync(join(tmpdir(), 'twrp-devices-'))
const tarball = join(work, 'twrpme.tar.gz')
writeFileSync(tarball, Buffer.from(await (await fetch(TARBALL_URL)).arrayBuffer()))
execFileSync('tar', ['xzf', tarball, '-C', work])
const repoRoot = join(work, readdirSync(work).find((d) => d.startsWith('twrpme-')))

// --- parse every device file ----------------------------------------------

// Frontmatter in the source files is flat 'key: value' lines between '---'
// fences. Values may be double-quoted. Anything we do not need is ignored.
function parseFrontmatter(path) {
  const text = readFileSync(path, 'utf8')
  const match = text.match(/^---\s*\n(.*?)\n---\s*\n/s)
  if (!match) return null
  const data = {}
  for (const line of match[1].split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue
    const sep = line.indexOf(':')
    if (sep === -1) continue
    data[line.slice(0, sep).trim().toLowerCase()] = line
      .slice(sep + 1)
      .trim()
      .replace(/^"(.*)"$/, '$1')
  }
  return data
}

const deviceFiles = readdirSync(repoRoot, { withFileTypes: true })
  .filter((entry) => {
    if (!entry.isDirectory()) return false
    return entry.name.startsWith('_') && !entry.name.startsWith('_includes')
  })
  .flatMap((entry) =>
    readdirSync(join(repoRoot, entry.name))
      .filter((file) => file.endsWith('.markdown'))
      .map((file) => join(repoRoot, entry.name, file))
  )
  .sort()

const skipped = []
const droppedFolders = []
const variantFolders = { count: 0 }
const droppedMaintainers = { count: 0 }
const devices = []
for (const file of deviceFiles) {
  const data = parseFrontmatter(file)
  const rel = relative(repoRoot, file)
  if (!data) {
    skipped.push(`${rel}: no frontmatter`)
    continue
  }
  if (!importAll && !isCurrentStatus(data.supportstatus)) {
    skipped.push(`${rel}: status '${data.supportstatus ?? ''}'`)
    continue
  }
  if (!data.title || !data.oem || !data.codename) {
    skipped.push(`${rel}: missing title/oem/codename`)
    continue
  }
  // The upstream 'twrp' entry is an EMULATOR test target (title 'Android
  // Emulator'), not a physical device a visitor can root — and it renders
  // as a brand literally named 'TWRP' on the catalog index, which the
  // 2026-11-08 general-catalog ruling forbids. Exclude it.
  if (String(data.codename).toLowerCase() === 'twrp') {
    skipped.push(`${rel}: emulator test target, not a physical device`)
    continue
  }
  const device = {
    title: decodeEntities(data.title),
    oem: decodeEntities(data.oem),
    codename: decodeEntities(data.codename),
    // Normalized to display casing 'Current' for the Current-only import;
    // with --all the raw upstream value is kept (layout must handle it).
    supportstatus: isCurrentStatus(data.supportstatus) ? 'Current' : data.supportstatus,
    maintainers: cleanMaintainers(data.maintainer),
    // 'device tree' (with a space) is a real upstream variant of the key.
    devicetree: data.devicetree || data['device tree'] || undefined,
    downloadfolder: data.downloadfolder || undefined,
  }
  if (device.maintainers.length === 0) {
    droppedMaintainers.count += 1
  }
  if (device.downloadfolder && !isDownloadFolder(device.downloadfolder)) {
    // Not a single canonical folder: try the multi-SKU parser (labeled
    // per-variant mirrors); drop only when even that fails — never guess.
    const variants = parseDownloadVariants(device.downloadfolder)
    if (variants.length > 0) {
      device.variants = variants
      variantFolders.count += 1
    } else {
      droppedFolders.push(`${device.codename}: '${device.downloadfolder}'`)
    }
    device.downloadfolder = undefined
  }
  devices.push(device)
}

// --- allocate slugs (deterministic; see header comment) -------------------

devices.sort((a, b) =>
  a.oem.toLowerCase().localeCompare(b.oem.toLowerCase()) ||
  a.title.toLowerCase().localeCompare(b.title.toLowerCase())
)
const slugMap = new Map()
const collisions = []
{
  const baseByDevice = new Map()
  for (const device of devices) baseByDevice.set(device, slugify(device.codename))
  const allocated = allocateSlugs(devices)
  for (const [device, slug] of allocated) {
    slugMap.set(device, slug)
    const base = baseByDevice.get(device)
    if (slug !== base) {
      collisions.push(`${base} -> ${slug} (${device.oem} ${device.title})`)
    }
  }
}

// --- regenerate the collection (self-cleaning via the marker) -------------

const today = new Date().toISOString().slice(0, 10)
let removed = 0
try {
  for (const file of readdirSync(OUT_DIR)) {
    if (!file.endsWith('.md')) continue
    const path = join(OUT_DIR, file)
    if (readFileSync(path, 'utf8').includes(MARKER)) {
      rmSync(path)
      removed += 1
    }
  }
} catch {
  // OUT_DIR does not exist yet — first import.
}

mkdirSync(OUT_DIR, { recursive: true })

// YAML 1.2 is a superset of JSON: JSON.stringify is a complete, safe
// escaping for every scalar (quotes, colons, unicode titles, …).
for (const device of devices) {
  // The marker comment sits INSIDE the frontmatter block: markdown
  // frontmatter must start on the first line of the file, and a comment
  // above the fence makes the parser treat the whole block as body text.
  const lines = ['---', `# ${MARKER} Re-run to re-sync.`]
  lines.push(`title: ${JSON.stringify(device.title)}`)
  lines.push(`oem: ${JSON.stringify(device.oem)}`)
  lines.push(`codename: ${JSON.stringify(device.codename)}`)
  lines.push(`supportstatus: ${JSON.stringify(device.supportstatus)}`)
  if (device.maintainers.length > 0) {
    lines.push('maintainer:')
    for (const name of device.maintainers) lines.push(`  - ${JSON.stringify(name)}`)
  }
  if (device.devicetree) lines.push(`devicetree: ${JSON.stringify(device.devicetree)}`)
  if (device.downloadfolder) {
    lines.push(`downloadfolder: ${JSON.stringify(device.downloadfolder)}`)
  }
  if (device.variants) {
    lines.push('variants:')
    for (const variant of device.variants) {
      lines.push(`  - label: ${JSON.stringify(variant.label)}`)
      lines.push(`    folder: ${JSON.stringify(variant.folder)}`)
    }
  }
  const extra = overrides.get(slugMap.get(device))
  if (extra) {
    for (const key of ['factoryimages', 'notes']) {
      if (extra[key] !== undefined) lines.push(`${key}: ${JSON.stringify(extra[key])}`)
    }
    for (const k of Object.keys(extra).filter((k) => !['factoryimages', 'notes'].includes(k))) {
      console.log(`override ${slugMap.get(device)}: unknown key '${k}' ignored`)
    }
  }
  lines.push(`updated: ${today}`)
  lines.push('---', '')
  writeFileSync(join(OUT_DIR, `${slugMap.get(device)}.md`), lines.join('\n'))
}

rmSync(work, { recursive: true, force: true })

// --- report ----------------------------------------------------------------

console.log(`imported ${devices.length} devices (${deviceFiles.length} files scanned)`)
console.log(`removed ${removed} stale generated files`)
console.log(`slug collisions resolved: ${collisions.length}`)
for (const line of collisions) console.log(`  ${line}`)
console.log(`devices without a listed maintainer: ${droppedMaintainers.count}`)
console.log(`multi-folder devices parsed into variants: ${variantFolders.count}`)
console.log(`download folders dropped (unparsable, no variants): ${droppedFolders.length}`)
for (const line of droppedFolders) console.log(`  ${line}`)
const skippedByReason = new Map()
for (const line of skipped) {
  const reason = line.split(': ').slice(1).join(': ')
  skippedByReason.set(reason, (skippedByReason.get(reason) ?? 0) + 1)
}
console.log(`skipped: ${skipped.length}`)
for (const [reason, count] of [...skippedByReason].sort()) {
  console.log(`  ${count}× ${reason}`)
}
