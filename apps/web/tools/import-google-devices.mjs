#!/usr/bin/env node
// tools/import-google-devices.mjs — generate Google Pixel device entries for
// the /device content collection (src/content/devices/*.md), covering the
// modern Pixels that the TWRP device list does NOT carry. Page prose lives in
// src/layouts/Device.astro; these files are frontmatter only.
//
// WHY: owner ruling 2026-11-08 — "ALL the latest Google devices added, with
// as much information as can be verified."
//
// SOURCES (authoritative, fetched fresh on every run):
//   1. Google's own Play Console supported-devices CSV
//      (storage.googleapis.com/play_public/supported_devices.csv, UTF-16LE):
//      the codename <-> model mapping is Google's official published data.
//   2. The TeamWin/twrpme tarball (same source as import-twrp-devices.mjs):
//      any codename present there — under ANY support status — is SKIPPED.
//      Those devices belong to the TWRP import pipeline (run
//      import-twrp-devices.mjs FIRST); importing them here too could
//      contradict a real upstream status (e.g. walleye = 'Beta',
//      crosshatch = 'Current-ish' on 2026-11-08).
//   3. developers.google.com/android/images — the factory-image archive link
//      and the anti-rollback cautions in ANTI_ROLLBACK_NOTES (verified in the
//      page's static HTML 2026-11-08; notes are ORIGINAL prose paraphrasing
//      Google's warnings, never copied text).
//
// SCOPE: devices whose Google-published marketing/model name starts with
// 'Pixel', excluding Pixel Watch (Wear OS) and Pixel Slate (ChromeOS) — this
// catalog's rooting/recovery content covers Android phones and tablets only.
// Devices already in src/content/devices (by codename, any importer) are
// skipped.
//
// STATUS FIELD: 'No official TWRP build listed' — a statement about the
// TWRP device catalog we mirror (verified by source 2 above), NOT a claim
// that no build could ever exist.
//
// SLUGS: slugify(codename) via src/lib/devices.js. Collisions among this
// batch resolve via allocateSlugs (<base>-google…); a slug whose file
// already exists on disk under a DIFFERENT codename (cross-importer
// collision) gets '-google' appended. Deterministic.
//
// SELF-CLEANING like the TWRP importer, but keyed on THIS script's marker
// comment only — it never touches TWRP-imported or hand-made files, and the
// TWRP importer's marker-based cleaning never touches these.
//
// Usage: node tools/import-google-devices.mjs

import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { allocateSlugs, slugify } from '../src/lib/devices.js'

const MARKER = 'Generated by tools/import-google-devices.mjs — do not edit by hand.'
const CSV_URL = 'https://storage.googleapis.com/play_public/supported_devices.csv'
const FACTORY_IMAGES_URL = 'https://developers.google.com/android/images'
const TWRP_TARBALL_URL = 'https://codeload.github.com/TeamWin/twrpme/tar.gz/refs/heads/master'
const OUT_DIR = fileURLToPath(new URL('../src/content/devices', import.meta.url))

// --- anti-rollback cautions (source 3; ORIGINAL prose) --------------------
// Verified in the static HTML of developers.google.com/android/images on
// 2026-11-08, sections "Special instructions for updating Pixel devices to
// the May 2025 / May 2026 monthly release".
const may2025 =
  "Google's factory-image page warns that the May 2025 monthly update for this model raises the bootloader's anti-rollback version. The first time you flash the May 2025 update or newer, flash the bootloader image to BOTH slots — otherwise a failed boot can fall back to the inactive slot's older bootloader and leave the device unbootable. Source: developers.google.com/android/images"
const may2026 =
  "Google's factory-image page warns that the May 2026 monthly update for this model raises the bootloader's anti-rollback version. The first time you flash the May 2026 update or newer, flash the bootloader image to BOTH slots — otherwise a failed boot can fall back to the inactive slot's older bootloader and leave the device unbootable. Source: developers.google.com/android/images"
const ANTI_ROLLBACK_NOTES = {
  // May 2025 note, named models: Pixel 6, 6 Pro, 6a, 8, 8 Pro, 8a.
  oriole: may2025,
  raven: may2025,
  bluejay: may2025,
  shiba: may2025,
  husky: may2025,
  akita: may2025,
  // May 2026 note, named models: Pixel 10, 10 Pro, 10 Pro XL, 10 Pro Fold.
  frankel: may2026,
  blazer: may2026,
  mustang: may2026,
  rango: may2026,
}

// --- fetch + parse Google's supported-devices CSV --------------------------

const csvBuffer = Buffer.from(execFileSync('curl', ['-sL', CSV_URL], { maxBuffer: 32 * 1024 * 1024 }).buffer)
// The CSV is UTF-16LE with a BOM (verified 2026-11-08).
const csvText = new TextDecoder('utf-16le').decode(csvBuffer).replace(/^\uFEFF/, '').replace(/\r/g, '')

// Minimal quoted-CSV row split (columns contain no embedded quotes in the
// Google rows; verified against the fetched file). Header: Retail Branding,
// Marketing Name, Device, Model.
function parseRow(line) {
  if (!line.startsWith('"') || !line.endsWith('"')) return null
  const parts = line.slice(1, -1).split('","')
  if (parts.length !== 4) return null
  return { brand: parts[0], marketing: parts[1], device: parts[2], model: parts[3] }
}

const pixelByCodename = new Map() // codename -> display name
const malformedRows = []
for (const line of csvText.split('\n').slice(1)) {
  if (!line.trim()) continue
  const row = parseRow(line)
  if (!row) {
    malformedRows.push(line.slice(0, 80))
    continue
  }
  if (row.brand.toLowerCase() !== 'google') continue
  if (row.device.endsWith('_cheets')) continue // ChromeOS devices (Chromebooks)
  // Display name: both the marketing and the model column are candidates
  // (their relative cleanliness varies per row — e.g. barbet has marketing
  // 'Pixel 5a 5G' but model 'Pixel 5a'); keep only Pixel-branded Android
  // phones/tablets, then prefer the SHORTEST passing candidate.
  // Exclusions: Pixel Watch (Wear OS — case-insensitive: some model strings
  // read 'Pixel watch 3'), Pixel Slate and Pixelbook (ChromeOS).
  const candidates = [row.marketing, row.model].filter(
    (name) =>
      name.startsWith('Pixel') &&
      !name.toLowerCase().includes('watch') &&
      !name.includes('Slate') &&
      !name.startsWith('Pixelbook'),
  )
  if (candidates.length === 0) continue
  const name = candidates.reduce((a, b) => (b.length < a.length ? b : a))
  const existing = pixelByCodename.get(row.device)
  if (existing === undefined || name.length < existing.length) {
    pixelByCodename.set(row.device, name)
  }
}

// Sanity guard: the modern Pixel line alone (1 through 11 + a/Pro/XL/Fold +
// Tablet) is well over twenty entries — anything less means Google's CSV
// format changed and this script must be re-verified before trusting output.
if (pixelByCodename.size < 20) {
  console.error(`ABORT: only ${pixelByCodename.size} Pixel devices parsed — upstream format changed?`)
  process.exit(1)
}

// --- codenames to skip: existing catalog files + the twrpme source ---------
// NOTE ORDERING: self-cleaning (below) runs BEFORE this scan, so files this
// script itself generated on a previous run are already gone and get freshly
// re-imported instead of being mistaken for foreign files to skip. Files
// from OTHER sources (TWRP importer, hand-made) are never deleted by the
// cleaning, so skipping them here works either way.

let removed = 0
try {
  for (const file of readdirSync(OUT_DIR)) {
    if (!file.endsWith('.md')) continue
    const path = join(OUT_DIR, file)
    if (readFileSync(path, 'utf8').includes(MARKER)) {
      rmSync(path)
      removed += 1
    }
  }
} catch {
  // OUT_DIR does not exist yet — first import.
}

const skipCodenames = new Set()
const codenameBySlugFile = new Map() // slug -> codename (existing files)
try {
  for (const file of readdirSync(OUT_DIR)) {
    if (!file.endsWith('.md')) continue
    const content = readFileSync(join(OUT_DIR, file), 'utf8')
    const m = content.match(/^codename: (".*")$/m)
    if (m) {
      const codename = JSON.parse(m[1])
      skipCodenames.add(codename)
      codenameBySlugFile.set(file.replace(/\.md$/, ''), codename)
    }
  }
} catch {
  // OUT_DIR does not exist yet — nothing to skip.
}

const work = mkdtempSync(join(tmpdir(), 'twrpme-google-check-'))
const repoRoot = join(work, 'repo')
mkdirSync(repoRoot)
execFileSync('curl', ['-sL', TWRP_TARBALL_URL, '-o', join(work, 'repo.tgz')])
execFileSync('tar', ['-xzf', join(work, 'repo.tgz'), '-C', repoRoot])
const top = readdirSync(repoRoot, { withFileTypes: true }).find((e) => e.isDirectory())
const twrpRoot = join(repoRoot, top.name)
const twrpCodenamesFound = []
for (const entry of readdirSync(twrpRoot, { withFileTypes: true })) {
  if (!entry.isDirectory() || !entry.name.startsWith('_')) continue
  for (const file of readdirSync(join(twrpRoot, entry.name))) {
    if (!file.endsWith('.markdown')) continue
    const content = readFileSync(join(twrpRoot, entry.name, file), 'utf8')
    const m = content.match(/^codename:\s*"?([^"\n]+?)"?\s*$/m)
    if (m) twrpCodenamesFound.push(m[1])
  }
}
for (const codename of twrpCodenamesFound) skipCodenames.add(codename)
rmSync(work, { recursive: true, force: true })

// --- build the device set + allocate slugs ---------------------------------

const skipped = []
const devices = []
for (const [codename, name] of [...pixelByCodename].sort()) {
  if (skipCodenames.has(codename)) {
    skipped.push(`${codename} (${name}): already covered by the TWRP import pipeline`)
    continue
  }
  devices.push({
    title: `Google ${name}`,
    oem: 'Google',
    codename,
    supportstatus: 'No official TWRP build listed',
    factoryimages: FACTORY_IMAGES_URL,
    notes: ANTI_ROLLBACK_NOTES[codename],
  })
}

devices.sort(
  (a, b) =>
    a.oem.toLowerCase().localeCompare(b.oem.toLowerCase()) ||
    a.title.toLowerCase().localeCompare(b.title.toLowerCase()),
)
const slugMap = new Map()
{
  const allocated = allocateSlugs(devices)
  for (const [device, slug] of allocated) {
    let final = slug
    // Cross-importer collision: a file with this slug already exists under a
    // DIFFERENT codename — disambiguate deterministically.
    const existingCodename = codenameBySlugFile.get(final)
    if (existingCodename !== undefined && existingCodename !== device.codename) {
      final = `${slug}-google`
      let n = 2
      while (codenameBySlugFile.has(final)) {
        final = `${slug}-google-${n}`
        n += 1
      }
    }
    slugMap.set(device, final)
    codenameBySlugFile.set(final, device.codename)
  }
}

// --- regenerate: write the fresh files (cleaning already ran above) -------

mkdirSync(OUT_DIR, { recursive: true })
const today = new Date().toISOString().slice(0, 10)
for (const device of devices) {
  // Marker comment INSIDE the frontmatter fence (see import-twrp-devices.mjs).
  const lines = ['---', `# ${MARKER} Re-run to re-sync.`]
  lines.push(`title: ${JSON.stringify(device.title)}`)
  lines.push(`oem: ${JSON.stringify(device.oem)}`)
  lines.push(`codename: ${JSON.stringify(device.codename)}`)
  lines.push(`supportstatus: ${JSON.stringify(device.supportstatus)}`)
  lines.push(`factoryimages: ${JSON.stringify(device.factoryimages)}`)
  if (device.notes) lines.push(`notes: ${JSON.stringify(device.notes)}`)
  lines.push(`updated: ${today}`)
  lines.push('---', '')
  writeFileSync(join(OUT_DIR, `${slugMap.get(device)}.md`), lines.join('\n'))
}

// --- report -----------------------------------------------------------------

console.log(`Pixel devices in Google's CSV: ${pixelByCodename.size}`)
console.log(`twrpme codenames checked: ${twrpCodenamesFound.length}`)
console.log(`imported ${devices.length} new Google device pages`)
for (const device of devices) console.log(`  ${device.codename} -> ${slugMap.get(device)} (${device.title})`)
console.log(`removed ${removed} stale generated files`)
console.log(`skipped (already covered by the TWRP pipeline): ${skipped.length}`)
for (const line of skipped) console.log(`  ${line}`)
console.log(`devices with anti-rollback notes: ${devices.filter((d) => d.notes).length}`)
if (malformedRows.length > 0) {
  console.log(`malformed CSV rows (ignored): ${malformedRows.length}`)
}
