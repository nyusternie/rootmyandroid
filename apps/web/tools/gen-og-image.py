#!/usr/bin/env python3
# apps/web/tools/gen-og-image.py
"""Composite public/og-image.png (1200x630): AI mascot art + local Inter type.

The mascot art is generated by an image LLM (see the image-generation skill)
and committed at tools/assets/mascot-v1.jpg; typography is composited here
with Inter (tools/fonts/, OFL) so rendering is pixel-exact and regenerating
never risks mangled text. Default headline: the hero H1.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)  # apps/web
MASCOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'assets', 'mascot-v2.jpg')
FONT = os.path.join(HERE, 'fonts', 'Inter.ttf')
OUT = os.path.join(ROOT, 'public', 'og-image.png')

S = 2  # supersample
W, H = 1200 * S, 630 * S
ACCENT = (61, 157, 242)  # --color-accent #3d9df2
WHITE = (234, 241, 250)
DIM = (138, 184, 232)

HEADLINE = [
    [('Unlock the ', WHITE), ('FULL', ACCENT)],
    [('power of your', WHITE)],
    [('Android phone.', WHITE)],
]
SUBLINE = 'rootmyandroid.com'


def inter(size, name):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_name(name)
    return f


def main():
    m = Image.open(MASCOT).convert('RGB')
    side = min(m.size)
    m = m.crop(((m.width - side) // 2, (m.height - side) // 2,
                (m.width + side) // 2, (m.height + side) // 2)).resize((H, H), Image.LANCZOS)
    bg = m.getpixel((8, 8))  # mascot's own corner color = canvas base
    img = Image.new('RGB', (W, H), bg)
    img.paste(m, (0, 0))
    # fade mascot tile's right edge into the canvas base
    fade = Image.new('L', (W, H), 0)
    fd = ImageDraw.Draw(fade)
    x0 = H - 260 * S
    for x in range(x0, H):
        fd.line([(x, 0), (x, H)], fill=int(255 * (x - x0) / (H - x0)))
    img.paste(Image.new('RGB', (W, H), bg), (0, 0), fade)

    d = ImageDraw.Draw(img)
    size = 130 * S
    f_head = inter(size, 'Bold')
    tx = H + 40 * S  # text zone, right of the mascot tile
    maxw = W - tx - 60 * S
    while size > 40:
        widest = max(sum(f_head.getlength(t) for t, _ in segs) for segs in HEADLINE)
        if widest <= maxw:
            break
        size -= 2
        f_head = inter(size, 'Bold')
    lh = int(size * 1.16)
    y = (H - lh * len(HEADLINE)) // 2 - 20 * S
    for segs in HEADLINE:
        x = tx
        for t, c in segs:
            d.text((x, y), t, font=f_head, fill=c)
            x += f_head.getlength(t)
        y += lh
    f_sub = inter(int(size * 0.36), 'Medium')
    d.text((tx, y + 26 * S), SUBLINE, font=f_sub, fill=DIM)

    img = img.resize((1200, 630), Image.LANCZOS)
    img.save(OUT, optimize=True)
    print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')


if __name__ == '__main__':
    main()
